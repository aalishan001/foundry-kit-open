#!/usr/bin/env python3
"""Render the OpenCode target from the Claude Code sources, so the two never drift apart.
  gen_opencode.py          write kit/.opencode/commands/*.md, kit/.opencode/agents/*.md, kit/AGENTS.md, kit/opencode.json
  gen_opencode.py --check  exit 1 if any generated file differs from what's in kit/ (the tests run this)
Sources: kit/.claude/commands/*.md, kit/.claude/agents/*.md, kit/CLAUDE.md, and scripts/opencode_models.json (which
model each command runs on). Edit the sources, never the generated files.
"""
import json, pathlib, re, sys

REPO = pathlib.Path(__file__).resolve().parent.parent
KIT = REPO / "kit"
MODELS = json.loads((REPO / "scripts" / "opencode_models.json").read_text(encoding="utf-8"))
HEADER = "<!-- Generated by scripts/gen_opencode.py from {src}. Edit the source, not this file. -->\n"

def split(text):
    m = re.match(r"^---\n(.*?)\n---\n(.*)$", text, re.S)
    if not m: raise SystemExit("a command file has no frontmatter")
    fm = {}
    for line in m.group(1).splitlines():
        k, _, v = line.partition(":")
        fm[k.strip()] = v.strip().strip('"')
    return fm, m.group(2)

def q(s): return json.dumps(s, ensure_ascii=False)

def model(tier): return MODELS["tiers"][tier]

def command(path):
    fm, body = split(path.read_text(encoding="utf-8"))
    name = path.stem
    tier = MODELS["commands"].get(name) or sys.exit(f"{name} has no tier in scripts/opencode_models.json")
    head = ["---", f"description: {q(fm['description'])}", f"model: {model(tier)}", "agent: build", "---"]
    rule = "In bash, run only one `python engine/<script>.py ...` command per call (never `python -c`, `Get-ChildItem`, `Get-Content`, `Test-Path` or pipes `|`); use the `read`, `glob`, `list`, `write` and `edit` tools for files.\n\n"
    tail = "\nArguments for this command: $ARGUMENTS\n"
    return "\n".join(head) + "\n" + HEADER.format(src=f".claude/commands/{path.name}") + rule + body.rstrip("\n") + "\n" + tail

def agent(path):
    fm, body = split(path.read_text(encoding="utf-8"))
    tier = MODELS["agents"].get(path.stem, "standard")
    head = ["---", f"description: {q(fm['description'])}", "mode: subagent", f"model: {model(tier)}",
            "permission:", "  edit: deny", "  bash: deny", "  webfetch: deny", "  task: deny", "---"]
    return "\n".join(head) + "\n" + HEADER.format(src=f".claude/agents/{path.name}") + body

APP_NOTE = """
## In OpenCode

- Web search and web fetch are off in this app (they would send the user's data to services that keep it). Read postings
  and careers pages only through `python engine/fetch.py text <url>`. Where a command says to search the web, say
  what you would look up, and ask the user to paste it or record it as unknown.
- In the `bash` tool, only `python engine/<script>.py ...` is allowed without a prompt: run one `python engine/...`
  command per call, with no shell pipelines (`|`), redirections (`2>&1`), or shell commands (`Get-Content`,
  `Get-ChildItem`, `Test-Path`, `Select-Object`, `head`, `echo`). To read or list files in the folder, always use the
  file-reading and listing tools (`read`, `glob`, `list`), never `bash`.
- Run the claim-checker as a subagent (the Task tool, agent `claim-checker`).
- Everything else is exactly as in the commands: the same engine, the same files, the same rules.
"""

def agents_md():
    src = (KIT / "CLAUDE.md").read_text(encoding="utf-8")
    return HEADER.format(src="CLAUDE.md") + src.rstrip("\n") + "\n" + APP_NOTE

KIT_DIRS = ["engine", "packs", "templates", "docs", ".claude", ".opencode"]
KIT_FILES = ["AGENTS.md", "CLAUDE.md", "opencode.json", "VERSION", "setup.ps1", "setup.cmd", "Gmail setup.cmd", "API keys.cmd", "OpenCode.cmd"]

def opencode_json():
    """OpenCode 1.x config (V1 keys). Only OpenRouter is enabled, and every request asks it for zero-data-retention,
    no-training endpoints; web search and web fetch are off; kit files can't be edited."""
    edit = {"*": "allow"}
    edit.update({f"{d}/*": "deny" for d in KIT_DIRS})
    edit.update({f: "deny" for f in KIT_FILES})
    bash = {"*": "ask"}
    bash.update({f"{exe} engine/*": "allow" for exe in ("python", "py", "py -3")})
    used = sorted({m.split("/", 1)[1] for m in MODELS["tiers"].values()})
    route = {"provider": {"zdr": True, "data_collection": "deny", "allow_fallbacks": True}}
    cfg = {
        "$schema": "https://opencode.ai/config.json",
        "model": model(MODELS["default"]),
        "small_model": model(MODELS["background"]),
        "enabled_providers": ["openrouter"],
        "share": "disabled",
        "autoupdate": False,
        "provider": {"openrouter": {
            "options": {"apiKey": "{env:FOUNDRY_OPENROUTER_KEY}"},
            "models": {m: {"options": route} for m in used}}},
        "permission": {"*": "ask", "read": "allow", "glob": "allow", "grep": "allow", "list": "allow", "todowrite": "allow",
                       "question": "allow", "edit": edit, "bash": bash, "webfetch": "deny", "websearch": "deny",
                       "external_directory": "deny", "task": {"*": "deny", "claim-checker": "allow"}},
    }
    return json.dumps(cfg, indent=1, ensure_ascii=False) + "\n"

def render():
    out = {}
    for p in sorted((KIT / ".claude" / "commands").glob("*.md")): out[f".opencode/commands/{p.name}"] = command(p)
    for p in sorted((KIT / ".claude" / "agents").glob("*.md")): out[f".opencode/agents/{p.name}"] = agent(p)
    out["AGENTS.md"] = agents_md()
    out["opencode.json"] = opencode_json()
    return out

def main(a):
    files = render()
    stale = [n for n in (KIT / ".opencode").rglob("*.md")] if (KIT / ".opencode").exists() else []
    extra = [p for p in stale if p.relative_to(KIT).as_posix() not in files]
    diff = [n for n, t in files.items() if not (KIT / n).exists() or (KIT / n).read_text(encoding="utf-8") != t] + [p.relative_to(KIT).as_posix() for p in extra]
    if "--check" in a:
        if diff: print("OpenCode target is out of date (run scripts/gen_opencode.py): " + ", ".join(diff)); return 1
        print(f"OpenCode target up to date ({len(files)} files)"); return 0
    for n, t in files.items():
        p = KIT / n; p.parent.mkdir(parents=True, exist_ok=True); p.write_text(t, encoding="utf-8", newline="\n")
    for p in extra: p.unlink()
    print(f"wrote {len(files)} files" + (f"; removed {len(extra)} stale" if extra else ""))
    return 0

if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
